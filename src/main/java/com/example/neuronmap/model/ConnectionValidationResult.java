package com.example.neuronmap.model;

/**
 * Описує результат перевірки допустимості напрямленого зв’язку між двома нейронами карти.
 */
public enum ConnectionValidationResult {
    /** Пара нейронів відповідає всім правилам створення зв’язків. */
    VALID,
    /** Один із кінців зв’язку не існує в поточній моделі. */
    INVALID_ENDPOINT,
    /** Джерело та ціль є тим самим нейроном. */
    SELF_CONNECTION,
    /** Такий напрямлений зв’язок уже існує. */
    ALREADY_EXISTS,
    /** Структурний контейнер намагаються з’єднати зі звичайним нейроном. */
    STRUCTURE_ENDPOINT_TYPE_MISMATCH,
    /** Обидва нейрони належать одній структурі або одному дереву вкладених структур. */
    SAME_STRUCTURE_SCOPE
}
