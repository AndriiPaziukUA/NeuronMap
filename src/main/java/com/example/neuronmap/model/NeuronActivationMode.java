package com.example.neuronmap.model;

/** Визначає, яким способом нейрон оцінює отримані сигнали перед активацією. */
public enum NeuronActivationMode {
    /** Сигнали підсумовуються з урахуванням їхньої сили та знака. */
    SIGNAL_STRENGTH,

    /** Кожен збуджувальний вхід додає одиницю, а гальмівний віднімає одиницю. */
    SIGNAL_COUNT
}
