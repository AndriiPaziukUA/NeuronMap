package com.example.neuronmap.model;

/**
 * Визначає умову, за якою структура створює новий спільний нейрон для активованих джерел.
 * Значення є спільним для всього дерева структури та успадковується вкладеними учасниками.
 */
public enum StructureNeuronCreationMode {

    /** Зберігає чинну поведінку: достатньо непорожньої групи активованих нейронів. */
    NEURON_COUNT,

    /** Вимагає хоча б одного активного звичайного нейрона в кожній під'єднаній структурі-джерелі. */
    STRUCTURE_COUNT
}
