package com.example.neuronmap.model;

/** Визначає спосіб формування сили вихідного сигналу активованого нейрона. */
public enum SignalType {
    /** Використовує задану силу сигналу без її адаптації. */
    STATIC,
    /** Збільшує власну силу лише після отримання сильнішого сигналу, що пройшов поріг. */
    STRONGEST,
    /** Замінює власну силу кожною отриманою сумою, що пройшла поріг. */
    RECEIVED
}
